// Writes workers/lib/dev-seed/alex/photos.ts from the photos in its assets folder,
// so the Worker carries the bytes without a binary loader. Run after changing a photo:
//   node scripts/seed-photos.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dir = "workers/lib/dev-seed/alex";
const manifest = JSON.parse(readFileSync(`${dir}/assets/manifest.json`, "utf8"));
const lines = manifest.map((a) => `\t"${a.assetId}": "${readFileSync(`${dir}/assets/${a.filename}`).toString("base64")}",`);
writeFileSync(`${dir}/photos.ts`, `// Generated by scripts/seed-photos.mjs from ./assets (see assets/manifest.json for sources and licenses). Do not edit.

export const PHOTO_BASE64 = {
${lines.join("\n")}
} as const;
`);
console.log(`wrote ${dir}/photos.ts: ${manifest.length} photos`);
